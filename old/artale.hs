-- Main datatypes

data Term = Constant String
          | Variable String
          | Attribute Term Term
          | Index Term [Term]
          | Tuple [Term]
          | Operation Term Term Term

data Literal = Positive Relation
             | Negative Relation

data Relation = Atom Term [Term]
              | Comparison Term Term Term

data Rule = Assertion [Literal]
          | Implication [Literal] [Literal]
          | Contradiction [Literal]

data Declaration = LetOrder Int String Term
                 | LetFill Int String Term
                 | LetEqual Term Term
                 | LetFunction String [Term] Term
                 | LetAttribute Term Term Term

data Statement = Declare Declaration
               | Assert Rule

data State = Store Members Values Attributes Indices Ranges Domains Images

type GroundTerm = [String]

type GroundAtom = [GroundTerm]

type Model = [GroundAtom]

-- Types used in output, reports and pretty-printing

data Error = NotAProgram
           | CyclicDependencies
           | UndefinedTerms

data Warning = EmptySort
             | UnevenIff

data Message = InvalidProgram [(Error, [String])]
             | SatisfiableInstance [Model]
             | UnsatisfiableInstance
             | WarningReport [(Warning, [String])]

data CNFAtom = Plain String | Strike String
data Clause = CNF [CNFAtom]

