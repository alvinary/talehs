-- Updating a State based on the content of declarations --------------------------------------

emptyState :: State
emptyState = Store mempty mempty mempty mempty mempty mempty mempty

-- Given a list of declarations, obtain the expected state
getState :: [Declaration] -> State
getState decls = accumulate decls emptyState

-- Fold a list of declarations and a state
accumulate :: [Declaration] -> State -> State
accumulate rest str = foldl (flip applyDeclaration) str rest

-- Apply a declaration to a state (i.e. 'update' the state to comply with the declaration)
applyDeclaration :: Declaration -> State -> State
applyDeclaration decl str = str

