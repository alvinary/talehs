-- Get a generic name for the ith element of a sort
name :: String -> Int -> String
name prefix n = prefix ++ "." ++ show n

-- Get n members with generic names for a sort
fillMembers :: Int -> String -> [String]
fillMembers n prefix = [ name prefix i | i <- [1..n] ]

-- Get the assignments encoding the 'next' relation of a totally ordered sort
orderAttributes :: Int -> String -> Attributes
orderAttributes size prefix = fromList [((name prefix i, "next"), name prefix (i + 1)) | i <- [1..size] ]

